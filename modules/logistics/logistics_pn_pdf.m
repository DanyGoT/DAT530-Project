% %%%%%%%   Logistikk avdeling
% To lagerplasser (Yard1, Yard2) med ulik avstand til verkstedet
% Lastebil kjører tom til en yard, laster med truck, kjører tilbake
% Lossing med truck på verkstedet -> Output buffer (rør levert)
% Avstand modelleres som firing time på kjøre-transitionene (settes i MSF)

function [pns] = logistics_pn_pdf()

pns.PN_name = 'Logistics Petri Net model';
pns.set_of_Ps = {Lgs.pYard1, Lgs.pYard2, Lgs.pTruckAvailable, ...
                 Lgs.pTruckAtYard1, Lgs.pTruckAtYard2, Lgs.pLoaded1, Lgs.pLoaded2, ...
                 Lgs.pForkliftYard1, Lgs.pForkliftYard2, Lgs.pForkliftWorkshop, ...
                 Lgs.pAtDestination, Lgs.pOutput};
pns.set_of_Ts = {Lgs.tDriveToYard1, Lgs.tDriveToYard2, Lgs.tLoad1, Lgs.tLoad2, ...
                 Lgs.tDriveFromYard1, Lgs.tDriveFromYard2, Lgs.tUnload};
pns.set_of_As = { ...
  Lgs.pTruckAvailable, Lgs.tDriveToYard1, 1, Lgs.pYard1, Lgs.tDriveToYard1, 1 ... % Drive empty to yard 1 (only if pipes there)
  Lgs.tDriveToYard1,   Lgs.pTruckAtYard1, 1 ...
  Lgs.pTruckAvailable, Lgs.tDriveToYard2, 1, Lgs.pYard2, Lgs.tDriveToYard2, 1 ... % Drive empty to yard 2
  Lgs.tDriveToYard2,   Lgs.pTruckAtYard2, 1 ...
  Lgs.pTruckAtYard1, Lgs.tLoad1, 1, Lgs.pForkliftYard1, Lgs.tLoad1, 1 ...         % Load at yard 1
  Lgs.tLoad1, Lgs.pLoaded1, 1, Lgs.tLoad1, Lgs.pForkliftYard1, 1 ...
  Lgs.pTruckAtYard2, Lgs.tLoad2, 1, Lgs.pForkliftYard2, Lgs.tLoad2, 1 ...         % Load at yard 2
  Lgs.tLoad2, Lgs.pLoaded2, 1, Lgs.tLoad2, Lgs.pForkliftYard2, 1 ...
  Lgs.pLoaded1, Lgs.tDriveFromYard1, 1, Lgs.tDriveFromYard1, Lgs.pAtDestination, 1 ... % Drive back from yard 1
  Lgs.pLoaded2, Lgs.tDriveFromYard2, 1, Lgs.tDriveFromYard2, Lgs.pAtDestination, 1 ... % Drive back from yard 2
  Lgs.pAtDestination, Lgs.tUnload, 1, Lgs.pForkliftWorkshop, Lgs.tUnload, 1 ...   % Unload at workshop
  Lgs.tUnload, Lgs.pOutput, 1, Lgs.tUnload, Lgs.pForkliftWorkshop, 1 ...
  Lgs.tUnload, Lgs.pTruckAvailable, 1 ...
 };
