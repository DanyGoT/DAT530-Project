  'pLLoaded1', 'tLDriveFromYard1', 1, 'tLDriveFromYard1', 'pLAtDestination', 1 ... % Drive back from yard 1
  'pLLoaded2', 'tLDriveFromYard2', 1, 'tLDriveFromYard2', 'pLAtDestination', 1 ... % Drive back from yard 2
  'pLAtDestination', 'tLUnload', 1, 'pLForkliftWorkshop', 'tLUnload', 1 ...   % Unload at workshop
  'tLUnload', 'pLOutput', 1, 'tLUnload', 'pLForkliftWorkshop', 1 ...
  'tLUnload', 'pLTruckAvailable', 1 ...
 };
