% PDF: wash_pdf.m
%
% %%%%%%%   Washing hall
% The machine's state is in places, one token each:
%   pWIdle / pWReady  - demobilized / mobilized
%   pWLong / pWShort  - set up for long or short joints
% tWMobilize runs when joints are waiting, tWDemobilize when none are left
% (inhibitor arc). tWToLong / tWToShort switch the machine when the next joint
% has the other length. tWLong / tWShort wash one joint.

function [png] = wash_pdf()

png.PN_name = 'Washing';
png.set_of_Ps = {'pWBuf', 'pWIdle', 'pWReady', 'pWLong', 'pWShort'};
png.set_of_Ts = {'tWMobilize', 'tWDemobilize', 'tWToLong', 'tWToShort', 'tWLong', 'tWShort'};
png.set_of_As = { ...
  'pWIdle',  'tWMobilize',   1, 'tWMobilize',   'pWReady', 1 ...
  'pWReady', 'tWDemobilize', 1, 'tWDemobilize', 'pWIdle',  1 ...
  'pWShort', 'tWToLong',     1, 'tWToLong',     'pWLong',  1 ...
  'pWLong',  'tWToShort',    1, 'tWToShort',    'pWShort', 1 ...
  'pWBuf', 'tWLong',  1, 'pWReady', 'tWLong',  1, 'pWLong',  'tWLong',  1 ...
  'tWLong',  'pWReady', 1, 'tWLong',  'pWLong',  1 ...
  'pWBuf', 'tWShort', 1, 'pWReady', 'tWShort', 1, 'pWShort', 'tWShort', 1 ...
  'tWShort', 'pWReady', 1, 'tWShort', 'pWShort', 1 ...
 };
png.set_of_Is = {'pWBuf', 'tWDemobilize', 1};
