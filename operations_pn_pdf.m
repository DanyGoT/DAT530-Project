% %%%%%%%   Operasjonell avdeling
% Input buffer
% Cleaning buffer
% Cleaning transition
% Cleaning to inspection transition
% Inspection buffer
% Inspection transition
% Inspection to output transition
% Output buffer

function [pns] = operations_pn_pdf()

pns.PN_name = 'Operations';
pns.set_of_Ps = {
    'pOCleaning', ...
    'pOCleaned', 'pOInspection', 'pOInspector', 'pODecision', ...
    'pOPassed', 'pOScrap', 'pOOutput', ...
    'pORepairMinor', 'pORepairModerate', 'pORepairMajor', ...
    'pRMinor', 'pRModerate', 'pRMajor', 'pRDone', ...
    'pRTransport', 'pRStation', 'pRWorkerL1', 'pRWorkerL2', 'pRWorkerL3', ...
    'pOReinspection', 'pOReDecision' ...
};
pns.set_of_Ts = {
    'tOCleaningInput', 'tOClean', ...
    'tOMoveToInspection', 'tOInspect', 'tOInspectionOutput', ...
    'tOPass', 'tOScrap', 'tOMinor', 'tOModerate', 'tOMajor', ...
    'tRReturn', 'tOReinspect', 'tORePass', 'tOReScrap' ...
};
pns.set_of_As = { ...
  'tOCleaningInput', 'pOCleaning', 1, ...
  'pOCleaning', 'tOClean', 1, 'tOClean', 'pOCleaned', 1, ...
  'pOCleaned', 'tOMoveToInspection', 1, 'tOMoveToInspection', 'pOInspection', 1, ...
  'pOInspection', 'tOInspect', 1, 'pOInspector', 'tOInspect', 1, ...
  'tOInspect', 'pODecision', 1, ...
  'pOPassed', 'tOInspectionOutput', 1, 'tOInspectionOutput', 'pOOutput', 1, ...
  'pRDone', 'tRReturn', 1, 'pRTransport', 'tRReturn', 1, ...
  'tRReturn', 'pOReinspection', 1, 'tRReturn', 'pRTransport', 1, ...
  'pOReinspection', 'tOReinspect', 1, 'pOInspector', 'tOReinspect', 1, ...
  'tOReinspect', 'pOReDecision', 1
 };

routeNames = {'tOPass', 'tOMinor', 'tOModerate', 'tOMajor', 'tOScrap', ...
              'tORePass', 'tOReScrap'};
routeOutputs = {'pOPassed', 'pORepairMinor', 'pORepairModerate', ...
                'pORepairMajor', 'pOScrap', 'pOPassed', 'pOScrap'};
for routeIndex = 1:numel(routeNames)
    decisionPlace = 'pODecision';
    if routeIndex > 5
        decisionPlace = 'pOReDecision';
    end
    pns.set_of_As = [pns.set_of_As, ...
        {decisionPlace, routeNames{routeIndex}, 1, ...
         routeNames{routeIndex}, routeOutputs{routeIndex}, 1, ...
         routeNames{routeIndex}, 'pOInspector', 1}];
end

repairNames = {'Minor', 'Moderate', 'Major'};
for difficulty = 1:numel(repairNames)
    repairName = repairNames{difficulty};
    transportName = ['tRTransport' repairName];
    pns.set_of_Ts{end+1} = transportName;
    pns.set_of_As = [pns.set_of_As, ...
        {['pORepair' repairName], transportName, 1, ...
         'pRTransport', transportName, 1, ...
         transportName, ['pR' repairName], 1, ...
         transportName, 'pRTransport', 1}];
    for workerLevel = difficulty:3
        transitionName = sprintf('tR%sL%d', repairName, workerLevel);
        workerPlace = sprintf('pRWorkerL%d', workerLevel);
        pns.set_of_Ts{end+1} = transitionName;
        pns.set_of_As = [pns.set_of_As, ...
            {['pR' repairName], transitionName, 1, ...
             workerPlace, transitionName, 1, 'pRStation', transitionName, 1, ...
             transitionName, 'pRDone', 1, transitionName, workerPlace, 1, ...
             transitionName, 'pRStation', 1}];
    end
end

pns.set_of_Ports = {'tOCleaningInput', 'tOInspectionOutput'};
